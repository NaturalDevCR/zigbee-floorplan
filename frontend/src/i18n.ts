const tables: Record<string, Partial<Record<I18nKey, string>>> = { en, es };

export type Translate = (key: I18nKey, vars?: Record<string, string | number>) => string;

export function translator(language: string | undefined): Translate {
  const lang = (language ?? "en").toLowerCase().split("-")[0];
  const table = tables[lang] ?? en;
  return (key, vars) => {
    let text: string = table[key] ?? en[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) text = text.replaceAll(`{${k}}`, String(v));
    return text;
  };
}

export function relativeTime(t: Translate, iso: string | null, now = Date.now()): string | null {
  if (!iso) return null;
  const ts = Date.parse(iso);
  if (Number.isNaN(ts)) return null;
  const min = Math.round((now - ts) / 60000);
  if (min < 1) return t("time.just_now");
  if (min < 60) return t("time.minutes", { n: min });
  const h = Math.round(min / 60);
  if (h < 48) return t("time.hours", { n: h });
  return t("time.days", { n: Math.round(h / 24) });
}
